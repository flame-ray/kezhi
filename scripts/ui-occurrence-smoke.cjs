const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path");
const { chromium } = require(process.env.KEZHI_PLAYWRIGHT_PATH || "playwright");
const base = process.env.KEZHI_UI_URL || "http://127.0.0.1:1421";
const out = path.resolve("tmp/ui-occurrence");
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    await context.route("**/*", r => new URL(r.request().url()).origin === base ? r.continue() : r.abort());
    const page = await context.newPage(), errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.goto(base);
    await page.evaluate(async () => {
      const { defaultPresets } = await import("/src/data/demo.ts");
      localStorage.setItem("kezhi.schedule.prototype.v2", JSON.stringify({ presets: defaultPresets, activePresetId: "summer", termStartsOn: "2026-09-14", teachingStartsOn: "2026-09-14", courses: [{ id: "math", courseCode: "TEST", title: "单次测试课", teacher: "教师", location: "A301", day: 1, startPeriod: 1, endPeriod: 2, color: "teal", weeks: [1, 2, 3] }] }));
    });
    await page.reload();
    const settle = () => page.waitForTimeout(400);
    const card = () => page.locator(".active-page .course-card").filter({ hasText: "单次测试课" });
    const snapshot = () => page.evaluate(() => JSON.parse(localStorage.getItem("kezhi.schedule.prototype.v2")));
    const open = async () => {
      await card().click(); await settle();
      await page.locator(".material-backdrop:not([inert]) .occurrence-action").click(); await settle();
    };
    await settle(); await open();
    await page.keyboard.press("Escape"); await settle();
    assert.equal(await page.locator(".occurrence-dialog").count(), 0);
    assert.equal(await page.locator(".material-backdrop:not([inert]) .occurrence-action").count(), 1);
    await page.locator(".material-backdrop:not([inert]) .occurrence-action").click(); await settle();
    const dialog = page.locator(".occurrence-dialog");
    await page.screenshot({ path: path.join(out, "move-light.png") });
    const bounds = await dialog.boundingBox();
    assert(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 845);
    await dialog.getByLabel("本次操作").selectOption("cancel");
    await dialog.getByRole("button", { name: "确认本次停课", exact: true }).click(); await settle();
    assert.match(await card().textContent(), /本次停课/);
    assert.deepEqual((await snapshot()).courses[0].weeks, [1, 2, 3]);
    assert.equal((await snapshot()).courseExceptions.length, 1);
    console.log("PASS one-date cancellation preserves recurring course and back closes only top dialog");
    await page.reload(); await settle();
    assert.match(await card().textContent(), /本次停课/);
    await page.screenshot({ path: path.join(out, "cancelled-week.png") });
    await open();
    await dialog.getByRole("button", { name: "撤销这次变更，恢复原课表" }).click(); await settle();
    assert(!/本次停课/.test(await card().textContent()));
    assert.equal((await snapshot()).courseExceptions.length, 0);
    console.log("PASS cancellation persists across reload and undo restores original occurrence");
    await page.getByRole("button", { name: "切换暗色主题", exact: true }).click(); await settle();
    await open();
    await dialog.getByLabel("调至日期").fill("2026-09-23");
    await dialog.getByLabel("开始节次").selectOption("3");
    await dialog.getByLabel("结束节次").selectOption("4");
    await dialog.getByLabel("本次教室").fill("B202");
    await page.waitForTimeout(3600);
    await page.screenshot({ path: path.join(out, "move-dark.png") });
    await dialog.getByRole("button", { name: "确认单次调课", exact: true }).click(); await settle();
    assert.match(await card().textContent(), /本次已调走/);
    await page.getByRole("button", { name: "下一周", exact: true }).click(); await settle();
    assert.equal(await card().count(), 2);
    const moved = card().filter({ hasText: "B202" });
    assert.equal(await moved.count(), 1);
    await moved.click(); await settle();
    await page.locator(".material-backdrop:not([inert]) .occurrence-action").click(); await settle();
    assert.equal(await dialog.getByLabel("调至日期").inputValue(), "2026-09-23");
    assert.match(await dialog.textContent(), /原日期 2026-09-14/);
    await dialog.getByRole("button", { name: "撤销这次变更，恢复原课表" }).click(); await settle();
    assert.equal(await card().count(), 1);
    assert.equal((await snapshot()).courseExceptions.length, 0);
    console.log("PASS cross-week move changes date, periods and room; undo from destination works");
    await page.getByRole("button", { name: "上一周", exact: true }).click(); await settle(); await open();
    await dialog.getByLabel("调至日期").fill("2026-09-01");
    assert(await dialog.getByRole("button", { name: "确认单次调课", exact: true }).isDisabled());
    assert.match(await dialog.getByRole("alert").textContent(), /正式开课/);
    console.log("PASS invalid target date cannot be saved");
    await page.setViewportSize({ width: 320, height: 600 }); await settle();
    const footer = await dialog.locator(".dialog-footer").boundingBox();
    assert(footer.y >= 0 && footer.y + footer.height <= 601);
    await page.screenshot({ path: path.join(out, "move-small-screen.png") });
    await dialog.getByLabel("本次操作").selectOption("cancel");
    await dialog.getByRole("button", { name: "确认本次停课", exact: true }).click(); await settle();
    await page.setViewportSize({ width: 390, height: 844 }); await settle();
    await page.locator(".primary-navigation").getByRole("button", { name: "今天", exact: true }).click(); await settle();
    await page.getByRole("button", { name: "9 月 14 日，周一", exact: true }).click(); await settle();
    assert.match(await page.locator(".today-hero").textContent(), /0 门课程/);
    const agenda = page.locator(".day-pager-page:not([inert]) .agenda-course");
    assert.match(await agenda.textContent(), /本次停课/);
    await agenda.click(); await settle();
    await page.locator(".material-backdrop:not([inert]) .occurrence-action").click(); await settle();
    assert.match(await dialog.textContent(), /原日期 2026-09-14/);
    await dialog.getByRole("button", { name: "撤销这次变更，恢复原课表" }).click(); await settle();
    assert.match(await page.locator(".today-hero").textContent(), /1 门课程/);
    console.log("PASS small-screen footer reachable and Today uses selected date for undo");
    await agenda.click(); await settle();
    await page.locator(".material-backdrop:not([inert]) .occurrence-action").click(); await settle();
    await dialog.getByLabel("调至日期").fill("2026-09-21");
    const save = dialog.getByRole("button", { name: "确认单次调课", exact: true });
    assert(await save.isDisabled());
    const warning = dialog.getByRole("region", { name: "调课时间冲突" });
    assert.match(await warning.textContent(), /单次测试课/);
    const accept = warning.getByRole("checkbox");
    await accept.check();
    assert(await save.isEnabled());
    await dialog.getByLabel("调至日期").fill("2026-09-22");
    assert.equal(await warning.count(), 0);
    assert(await save.isEnabled());
    await dialog.getByLabel("调至日期").fill("2026-09-21");
    assert(await save.isDisabled());
    assert(!(await accept.isChecked()));
    await accept.check(); await page.waitForTimeout(400);
    await warning.scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, "conflict-confirm-dark.png") });
    await save.click(); await settle();
    assert.equal((await snapshot()).courseExceptions.length, 1);
    assert.deepEqual((await snapshot()).courses[0].weeks, [1, 2, 3]);
    console.log("PASS conflicts require explicit confirmation, reset after edits, and preserve other occurrences");
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
