const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { chromium } = require(process.env.KEZHI_PLAYWRIGHT_PATH || 'playwright');
const base = process.env.KEZHI_UI_URL || 'http://127.0.0.1:1421';
const out = path.resolve('tmp/ui-study-tasks'); fs.mkdirSync(out, { recursive: true });
(async () => {
 const browser = await chromium.launch({ headless: true });
 try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, timezoneId: 'Asia/Shanghai' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.clock.setFixedTime(new Date('2026-09-12T02:00:00Z'));
  const settle = () => page.waitForTimeout(450);
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('kezhi.schedule.prototype.v2')));
  await page.goto(base); await settle();
  await page.evaluate(async () => {
   const { demoCourses } = await import('/src/data/demo.ts');
   const key = 'kezhi.schedule.prototype.v2';
   const data = JSON.parse(localStorage.getItem(key));
   data.courses = demoCourses; data.exams = []; localStorage.setItem(key, JSON.stringify(data));
  });
  await page.reload(); await settle();
  const enterExams = async () => {
   await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '今天', exact: true }).click(); await settle();
   await page.getByRole('button', { name: '考试中心', exact: true }).click(); await settle();
  };
  await enterExams(); await page.getByRole('button', { name: '添加考试', exact: true }).click(); await settle();
  let editor = page.getByRole('dialog', { name: '添加考试', exact: true });
  const suggestions = editor.getByRole('combobox', { name: /从课表或成绩快速填写/ });
  assert.equal(await suggestions.locator('option').filter({ hasText: '大学英语（一）' }).count(), 1);
  const oldDate = await editor.getByLabel('考试日期', { exact: true }).inputValue();
  await suggestions.selectOption('大学英语（一）');
  assert.equal(await editor.getByLabel('考试名称', { exact: true }).inputValue(), '大学英语（一）');
  assert.equal(await editor.getByLabel('考场', { exact: true }).inputValue(), '');
  assert.equal(await editor.getByLabel('考试日期', { exact: true }).inputValue(), oldDate);
  console.log('PASS course suggestions deduplicate and only fill exam title');
  await editor.getByLabel('新复习任务', { exact: true }).fill('复习第一章');
  await editor.getByRole('button', { name: '添加任务', exact: true }).click();
  await editor.getByLabel('新复习任务', { exact: true }).fill('整理错题');
  await editor.getByLabel('新复习任务', { exact: true }).press('Enter');
  await editor.getByLabel('完成任务：复习第一章', { exact: true }).check();
  await editor.getByLabel('复习任务 2', { exact: true }).fill('整理词汇');
  await editor.getByRole('button', { name: '删除任务：整理词汇', exact: true }).click();
  await editor.getByRole('button', { name: '撤销删除任务', exact: true }).click();
  assert.equal(await editor.getByLabel('复习任务 2', { exact: true }).inputValue(), '整理词汇');
  await editor.locator('.study-editor').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'study-editor-light.png') });
  await editor.getByLabel('新复习任务', { exact: true }).fill('做一套模拟题');
  await editor.getByRole('button', { name: '保存考试', exact: true }).click(); await settle();
  let tasks = (await state()).exams[0].studyTasks;
  assert.equal(tasks.length, 3); assert.equal(tasks[0].done, true); assert.equal(tasks[2].title, '做一套模拟题');
  assert.match(await page.locator('.exam-card').textContent(), /复习 1 \/ 3/);
  console.log('PASS add, Enter, completion, rename, delete/undo and pending task saved without loss');
  await page.reload(); await settle(); await enterExams();
  await page.locator('.exam-card').click(); await settle();
  editor = page.getByRole('dialog', { name: '编辑考试', exact: true });
  await editor.getByLabel('完成任务：复习第一章', { exact: true }).uncheck();
  await editor.getByRole('button', { name: '取消', exact: true }).click(); await settle();
  assert.equal((await state()).exams[0].studyTasks[0].done, true);
  await page.locator('.exam-card').click(); await settle();
  await editor.getByLabel('复习任务 2', { exact: true }).fill('');
  await editor.getByRole('button', { name: '保存考试', exact: true }).click(); await settle();
  assert(await editor.getByRole('alert').count());
  assert.equal((await state()).exams[0].studyTasks[1].title, '整理词汇');
  await editor.getByLabel('复习任务 2', { exact: true }).fill('整理词汇');
  await editor.getByRole('button', { name: '取消', exact: true }).click(); await settle();
  console.log('PASS reload persists tasks, cancel discards changes, invalid tasks cannot overwrite data');
  await page.getByRole('button', { name: '切换暗色主题' }).click(); await settle();
  await page.screenshot({ path: path.join(out, 'study-cards-dark.png') });
  await page.setViewportSize({ width: 360, height: 740 });
  await page.locator('.exam-card').click(); await settle();
  await editor.locator('.study-editor').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'study-editor-dark-360.png') });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const footer = await editor.getByRole('button', { name: '保存考试', exact: true }).boundingBox();
  assert(footer.y >= 0 && footer.y + footer.height <= 740, 'save remains on screen');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert(await editor.locator('.study-progress i').evaluate(el => parseFloat(getComputedStyle(el).transitionDuration) <= 0.001));
  assert.deepEqual(errors, []);
  console.log('PASS narrow dark dialog, visible save button, reduced motion and no runtime errors');
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
